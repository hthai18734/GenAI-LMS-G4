const test = require('node:test');
const assert = require('node:assert/strict');
const crypto = require('node:crypto');
const mongoose = require('mongoose');
const fs = require('node:fs');
const User = require('../../src/model/identity/User');
const Course = require('../../src/model/learning/Course');
const Lesson = require('../../src/model/learning/Lesson');
const Section = require('../../src/model/learning/Section');
const Assignment = require('../../src/model/learning/Assignment');
const Submission = require('../../src/model/learning/AssignmentSubmission');
const Enrollment = require('../../src/model/learning/Enrollment');
const Quiz = require('../../src/model/learning/Quiz');
const Attempt = require('../../src/model/learning/QuizAttempt');
const VideoUpload = require('../../src/model/learning/VideoUpload');
const JWT = require('../../src/utils/auth/JWTUtil');
const services = require('../../src/composition/services');
const { app } = require('../../src/index');
test('Iteration 3 Huy: curriculum, assessment, gradebook, report and video HTTP/DB contracts', { skip: !process.env.TEST_MONGODB_URI }, async t => {
  const secret = process.env.JWT_ACCESS_SECRET; process.env.JWT_ACCESS_SECRET = crypto.randomBytes(32).toString('hex');
  await mongoose.connect(process.env.TEST_MONGODB_URI, { dbName: `ai_lms_huy_test_${crypto.randomBytes(6).toString('hex')}` });
  await Promise.all([Section.init(), Submission.init(), VideoUpload.init()]);
  const server = app.listen(0, '127.0.0.1'); await new Promise(r => server.once('listening', r));
  t.after(async () => { await new Promise(r => server.close(r)); await mongoose.connection.dropDatabase(); await mongoose.disconnect(); if (secret === undefined) delete process.env.JWT_ACCESS_SECRET; else process.env.JWT_ACCESS_SECRET = secret; });
  const teacher = await User.create({ fullName: 'Test Teacher', email: 'teacher@huy.test', role: 'teacher', emailVerifiedAt: new Date() });
  const other = await User.create({ fullName: 'Other', email: 'other@huy.test', role: 'teacher', emailVerifiedAt: new Date() });
  const student = await User.create({ fullName: 'Test Student', email: 'student@huy.test', role: 'student', emailVerifiedAt: new Date() });
  const course = await Course.create({ title: 'Test Course', teacherId: teacher._id, status: 'DRAFT' });
  const otherCourse = await Course.create({ title: 'Other', teacherId: other._id, status: 'DRAFT' });
  async function request(path, user = teacher, method = 'GET', body) {
    const headers = { ...(user ? { Authorization: `Bearer ${JWT.createAccessToken(user)}` } : {}) };
    if (!(body instanceof FormData)) headers['Content-Type'] = 'application/json';
    const res = await fetch(`http://127.0.0.1:${server.address().port}/api/${path}`, { method, headers, ...(body === undefined ? {} : { body: body instanceof FormData ? body : JSON.stringify(body) }) });
    return { status: res.status, body: await res.json() };
  }
  const sectionPath = `teacher/courses/${course._id}/sections`;
  assert.equal((await request(sectionPath, null)).status, 401);
  assert.equal((await request(sectionPath, other, 'POST', { title: 'No' })).status, 403);
  assert.equal((await request(sectionPath, teacher, 'POST', { title: '' })).status, 400);
  const first = (await request(sectionPath, teacher, 'POST', { title: 'Section 1' })).body.data.section;
  const second = (await request(sectionPath, teacher, 'POST', { title: 'Section 2' })).body.data.section;
  const foreign = await Section.create({ courseId: otherCourse._id, title: 'Foreign', order: 1 });
  const deletedSection = await Section.create({ courseId: course._id, title: 'Deleted', order: 99, deletedAt: new Date() });
  const lessonPath = `teacher/courses/${course._id}/lessons`;
  const payload = { title: 'Lesson', content: 'Notes', order: 1, sectionId: first._id, isPublished: true };
  assert.equal((await request(lessonPath, teacher, 'POST', { ...payload, sectionId: String(foreign._id) })).status, 404);
  assert.equal((await request(lessonPath, teacher, 'POST', { ...payload, sectionId: String(deletedSection._id) })).status, 404);
  const l1 = (await request(lessonPath, teacher, 'POST', payload)).body.data.lesson;
  const l2 = (await request(lessonPath, teacher, 'POST', { ...payload, order: 2 })).body.data.lesson;
  const l3 = (await request(lessonPath, teacher, 'POST', { ...payload, sectionId: second._id })).body.data.lesson;
  assert.equal((await request(`${lessonPath}/${l1._id}`, other, 'PATCH', { title: 'Denied' })).status, 403);
  assert.equal((await request(`${lessonPath}/${l1._id}`, teacher, 'PATCH', { sectionId: String(foreign._id) })).status, 404);
  assert.equal((await request(`${lessonPath}/reorder`, teacher, 'PUT', { sectionId: first._id, orderedLessonIds: [l1._id, l3._id] })).status, 409);
  assert.equal((await request(`${lessonPath}/reorder`, teacher, 'PUT', { sectionId: first._id, orderedLessonIds: [l2._id, l1._id] })).status, 200);
  const lessons = (await request(lessonPath)).body.data.lessons;
  assert.deepEqual(lessons.map(l => l._id), [l2._id, l1._id, l3._id]);
  assert.equal((await Lesson.findById(l3._id)).order, 1);
  const movedDefault = await request(`${lessonPath}/${l3._id}`, teacher, 'PATCH', { sectionId: null });
  assert.equal(movedDefault.status, 200);
  assert.notEqual(movedDefault.body.data.lesson.sectionId, second._id);
  assert.equal((await Section.findById(movedDefault.body.data.lesson.sectionId)).isDefault, true);
  assert.equal((await request(`${lessonPath}/${l3._id}`, teacher, 'PATCH', { sectionId: second._id })).status, 200);

  await t.test('video validates owner/format, attaches metadata and removes abandoned/failed uploads', async () => {
    const form = () => { const data = new FormData(); data.append('video', new Blob([Buffer.from('0000ftypisom000000000000')], { type: 'video/mp4' }), 'lesson.mp4'); return data; };
    const endpoint = `teacher/uploads/lesson-video?courseId=${course._id}`;
    assert.equal((await request(endpoint, other, 'POST', form())).status, 403);
    const bad = new FormData(); bad.append('video', new Blob(['not a video'], { type: 'video/mp4' }), 'bad.mp4');
    assert.equal((await request(endpoint, teacher, 'POST', bad)).status, 400);
    const upload = await request(endpoint, teacher, 'POST', form()); assert.equal(upload.status, 201);
    const videoRef = upload.body.data.videoUrl;
    const saved = await request(`${lessonPath}/${l1._id}`, teacher, 'PATCH', { videoRef }); assert.equal(saved.status, 200);
    assert.equal((await Lesson.findById(l1._id)).videoMetadata.mimeType, 'video/mp4');
    assert.equal((await request(`teacher/uploads/lesson-video/${upload.body.data.filename}`, teacher, 'DELETE')).status, 200);
    const media = await fetch(`http://127.0.0.1:${server.address().port}/api/media/lesson-videos/${upload.body.data.filename}`, { headers: { Authorization: `Bearer ${JWT.createAccessToken(other)}` } }); assert.equal(media.status, 403);
    const abandoned = (await request(endpoint, teacher, 'POST', form())).body.data;
    await VideoUpload.updateOne({ filename: abandoned.filename }, { expiresAt: new Date(0) }); await services.lessonVideoService.cleanupAbandoned();
    assert.equal(await VideoUpload.countDocuments({ filename: abandoned.filename }), 0);
    // Remove only the generated file owned by this fixture after removing its reference.
    await Lesson.updateOne({ _id: l1._id }, { videoRef: null });
    const storagePath = require('node:path').resolve(__dirname, '../../uploads/lesson-videos', upload.body.data.filename);
    if (fs.existsSync(storagePath)) fs.unlinkSync(storagePath);
  });
  const assignmentPath = `teacher/courses/${course._id}/assignments`;
  await t.test('scale locking is atomic against a concurrent first numerical grade', async () => {
    const repository = require('../../src/infrastructure/persistence/mongoose/repositories/learning/AssignmentRepository');
    const a = await Assignment.create({ courseId: course._id, title: 'Scale race', content: 'Test', maxScore: 10, passingScore: 5 });
    const [locked, changed] = await Promise.all([repository.lockScale(a._id, 10, 5), repository.update(a._id, { maxScore: 20 })]);
    assert.equal([locked, changed].filter(Boolean).length, 1);
    if (locked) assert.equal((await Assignment.findById(a._id)).maxScore, 10);
    else assert.equal(await repository.lockScale(a._id, 10, 5), null);
    await Assignment.deleteOne({ _id: a._id });
    const b = await Assignment.create({ courseId: course._id, title: 'Settings race', content: 'Test', maxScore: 10, passingScore: 5 });
    const expected = { maxScore: 10, passingScore: 5 };
    const settings = await Promise.all([repository.update(b._id, { maxScore: 6 }, expected), repository.update(b._id, { passingScore: 9 }, expected)]);
    assert.equal(settings.filter(Boolean).length, 1);
    const actual = await Assignment.findById(b._id); assert.ok(actual.passingScore <= actual.maxScore);
    await Assignment.deleteOne({ _id: b._id });
  });
  const created = await request(assignmentPath, teacher, 'POST', { title: 'Task', content: 'Answer', lessonId: l1._id, maxScore: 10, passingScore: 5, deadline: '2030-01-01T00:00:00Z' });
  assert.equal(created.status, 201); const assignment = created.body.data.assignment;
  await Course.updateOne({ _id: course._id }, { status: 'PUBLIC' });
  await Enrollment.create({ userId: student._id, courseId: course._id, status: 'active' });
  const submitted = await request(`student/assignments/${assignment._id}/submissions`, student, 'POST', { answer: 'Student solution' });
  assert.equal(submitted.status, 200); const submission = submitted.body.data.submission;
  const submissionPath = `teacher/assignment-submissions/${submission._id}`;
  assert.equal((await request(submissionPath, other)).status, 403);
  assert.equal((await request(`teacher/assignments/${assignment._id}/submissions`, other)).status, 403);
  assert.equal((await request(`teacher/assignments/${assignment._id}/submissions?limit=0`)).status, 400);
  assert.equal((await request(`${submissionPath}/grade`, teacher, 'PATCH', { score: 11 })).status, 400);
  const grade = { score: 0, revision: submission.revision, feedback: '<script>inert</script>' };
  const race = await Promise.all([request(`${submissionPath}/grade`, teacher, 'PATCH', grade), request(`${submissionPath}/grade`, teacher, 'PATCH', grade)]);
  assert.deepEqual(race.map(r => r.status).sort(), [200, 409]);
  let latest = (await request(submissionPath)).body.data.submission;
  const feedback = await request(`${submissionPath}/feedback`, teacher, 'PATCH', { feedback: 'Teacher feedback', revision: latest.revision }); assert.equal(feedback.status, 200); assert.equal(feedback.body.data.submission.score, 0);
  latest = feedback.body.data.submission;
  assert.equal((await request(`${submissionPath}/grade`, teacher, 'PATCH', { score: 8, revision: latest.revision })).status, 200);
  const visible = (await request(`student/courses/${course._id}/assignments`, student)).body.data.assignments[0];
  assert.equal(visible.latestSubmission.score, 8); assert.equal(visible.latestSubmission.feedback, 'Teacher feedback');
  const quiz = await Quiz.create({ courseId: course._id, title: 'Quiz', timeLimit: 10, passingScore: 50 });
  for (const [i, score] of [75, 50].entries()) await Attempt.create({ quizId: quiz._id, courseId: course._id, userId: student._id, status: 'submitted', score, passed: true, expiresAt: new Date(), submittedAt: new Date(1000 + i) });
  const gradebookPath = `teacher/courses/${course._id}/gradebook`;
  assert.equal((await request(gradebookPath, other)).status, 403); assert.equal((await request(gradebookPath, student)).status, 403);
  assert.equal((await request(gradebookPath)).body.data.rows[0].result.status, 'incomplete');
  const policy = { components: [{ key: `assignment:${assignment._id}`, weight: 40 }, { key: `quiz:${quiz._id}`, weight: 60 }], quizAttempt: 'best', decimals: 2, passingScore: 70, missing: 'incomplete' };
  assert.equal((await request(`${gradebookPath}/policy`, teacher, 'PUT', policy)).status, 410);
  const book = (await request(gradebookPath)).body.data;
  assert.equal(book.rows[0].cells.find(cell => cell.key === `quiz:${quiz._id}`).score, 50);
  assert.equal(book.rows[0].result.eligibleToComplete, false);
  const report = (await request(`teacher/courses/${course._id}/grade-report`)).body.data;
  assert.deepEqual(report.rows, book.rows);
  assert.equal((await request(`${gradebookPath}/calculate`, teacher, 'POST')).body.data.rows[0].result.status, 'incomplete');
  await Assignment.updateOne({ _id: assignment._id }, { deadline: new Date(0) });
  assert.equal((await request(`student/assignments/${assignment._id}/submissions`, student, 'POST', { answer: 'Late' })).status, 409);
  assert.equal((await Submission.findById(submission._id)).answer, 'Student solution');
  await Course.updateOne({ _id: course._id }, { status: 'APPROVED' });
  assert.equal((await request(`teacher/courses/${course._id}`, teacher, 'DELETE')).status, 200);
  assert.equal(await Section.countDocuments({ courseId: course._id, deletedAt: null }), 0);
  assert.equal(await Lesson.countDocuments({ courseId: course._id, deletedAt: null }), 0);
});
