const test = require('node:test');
const assert = require('node:assert/strict');
const crypto = require('node:crypto');
const fs = require('node:fs');
const path = require('node:path');
const mongoose = require('mongoose');
const User = require('../../src/model/identity/User');
const Course = require('../../src/model/learning/Course');
const Lesson = require('../../src/model/learning/Lesson');
const Assignment = require('../../src/model/learning/Assignment');
const Submission = require('../../src/model/learning/AssignmentSubmission');
const Enrollment = require('../../src/model/learning/Enrollment');
const Quiz = require('../../src/model/learning/Quiz');
const Attempt = require('../../src/model/learning/QuizAttempt');
const VideoProgress = require('../../src/model/learning/VideoProgress');
const Certificate = require('../../src/model/learning/Certificate');
const JWT = require('../../src/utils/auth/JWTUtil');
const services = require('../../src/composition/services');
const { app } = require('../../src/index');
test('unified completion, certificates and private assignment documents', { skip: !process.env.TEST_MONGODB_URI }, async t => {
  const secret = process.env.JWT_ACCESS_SECRET; process.env.JWT_ACCESS_SECRET = crypto.randomBytes(32).toString('hex');
  await mongoose.connect(process.env.TEST_MONGODB_URI, { dbName: `ai_lms_completion_test_${crypto.randomBytes(6).toString('hex')}` });
  await Promise.all([Certificate.init(), Submission.init()]);
  const server = app.listen(0, '127.0.0.1'); await new Promise(r => server.once('listening', r));
  const stored = new Set();
  t.after(async () => {
    for (const filename of stored) { const file = path.resolve(__dirname, '../../uploads/assignment-documents', filename); if (fs.existsSync(file)) fs.unlinkSync(file); }
    await new Promise(r => server.close(r)); await mongoose.connection.dropDatabase(); await mongoose.disconnect();
    if (secret === undefined) delete process.env.JWT_ACCESS_SECRET; else process.env.JWT_ACCESS_SECRET = secret;
  });
  const teacher = await User.create({ fullName: 'Teacher', email: 'teacher@completion.test', role: 'teacher', emailVerifiedAt: new Date() });
  const student = await User.create({ fullName: 'Student', email: 'student@completion.test', role: 'student', emailVerifiedAt: new Date() });
  const peer = await User.create({ fullName: 'Peer', email: 'peer@completion.test', role: 'student', emailVerifiedAt: new Date() });
  const other = await User.create({ fullName: 'Other', email: 'other@completion.test', role: 'teacher', emailVerifiedAt: new Date() });
  const course = await Course.create({ title: 'Completion test', teacherId: teacher._id, status: 'DRAFT', gradePolicy: { quizAttempt: 'best', passingScore: 99 } });
  const lesson = await Lesson.create({ courseId: course._id, title: 'Video lesson', content: 'Read', order: 1, isPublished: true, videoRef: 'https://example.test/lesson.mp4' });
  const enrollment = await Enrollment.create({ courseId: course._id, userId: student._id });
  await Enrollment.create({ courseId: course._id, userId: peer._id });
  async function request(endpoint, user = teacher, method = 'GET', body, binary = false) {
    const headers = user ? { Authorization: `Bearer ${JWT.createAccessToken(user)}` } : {};
    if (!(body instanceof FormData)) headers['Content-Type'] = 'application/json';
    const response = await fetch(`http://127.0.0.1:${server.address().port}/api/${endpoint}`, { method, headers, ...(body === undefined ? {} : { body: body instanceof FormData ? body : JSON.stringify(body) }) });
    return { status: response.status, body: binary ? Buffer.from(await response.arrayBuffer()) : await response.json() };
  }
  const pdf = Buffer.from('%PDF-1.4\nAssignment test document\n%%EOF');
  const docx = require('../fixtures/assignmentDocx');
  const multipart = (data, bytes = pdf, name = 'Document.pdf', type = 'application/pdf') => { const form = new FormData(); form.append('data', JSON.stringify(data)); form.append('file', new Blob([bytes], { type }), name); return form; };
  const endpoint = `teacher/courses/${course._id}/assignments`;
  let assignment, submission;
  await t.test('Teacher creates a prompt document; invalid contents and foreign ownership rejected', async () => {
    assert.equal((await request(endpoint, other, 'POST', multipart({ title: 'No', content: 'No' }))).status, 403);
    assert.equal((await request(endpoint, teacher, 'POST', multipart({ title: 'Spoof', content: 'No' }, Buffer.from('text')))).status, 400);
    assert.equal((await request(endpoint, teacher, 'POST', multipart({ title: 'Too large', content: 'No' }, Buffer.alloc(25 * 1024 * 1024 + 1)))).status, 400);
    const created = await request(endpoint, teacher, 'POST', multipart({ title: 'Assignment', content: 'Upload your solution', maxScore: 100, passingScore: 50, deadline: '2030-01-01T00:00:00Z' }));
    assert.equal(created.status, 201); assignment = created.body.data.assignment; stored.add(assignment.attachment.storageKey);
    assert.equal('path' in assignment.attachment, false);
    const updated = await request(`teacher/assignments/${assignment._id}`, teacher, 'PATCH', multipart({ title: 'Assignment', content: 'Updated instructions' }, docx, 'Updated.docx', 'application/vnd.openxmlformats-officedocument.wordprocessingml.document'));
    assert.equal(updated.status, 200); stored.add(updated.body.data.assignment.attachment.storageKey);
    assert.equal(fs.existsSync(path.resolve(__dirname, '../../uploads/assignment-documents', assignment.attachment.storageKey)), false);
    assignment = updated.body.data.assignment;
    await Course.updateOne({ _id: course._id }, { status: 'PUBLIC' });
    const downloaded = await request(`student/assignments/${assignment._id}/attachment`, student, 'GET', undefined, true);
    assert.equal(downloaded.status, 200); assert.deepEqual(downloaded.body, docx);
    assert.equal((await request(`student/courses/${course._id}/assignments`, student)).body.data.assignments[0].title, 'Assignment');
  });
  await t.test('Last lesson alone cannot issue certificate; watched video is read from real documents', async () => {
    const complete = `student/courses/${course._id}/lessons/${lesson._id}/complete`;
    assert.equal((await request(complete, student, 'POST', {})).status, 400);
    await VideoProgress.create({ studentId: student._id, videoId: String(lesson._id), lessonId: lesson._id, courseId: course._id, watchedPercent: 90 });
    const marked = await request(complete, student, 'POST', {});
    assert.equal(marked.status, 200); assert.equal(marked.body.data.isCompleted, false);
    assert.equal(await Certificate.countDocuments({ userId: student._id }), 0);
  });
  await t.test('File-only submission, private download, grade and latest quiz drive same completion', async () => {
    const submitted = await request(`student/assignments/${assignment._id}/submissions`, student, 'POST', multipart({ answer: '' }, pdf, 'Answer.pdf'));
    assert.equal(submitted.status, 200); submission = submitted.body.data.submission; stored.add(submission.attachment.storageKey);
    const fileUrl = `teacher/assignment-submissions/${submission._id}/attachment`;
    assert.equal((await request(fileUrl, teacher, 'GET', undefined, true)).status, 200);
    assert.equal((await request(fileUrl, other)).status, 403);
    assert.equal((await request(`student/assignment-submissions/${submission._id}/attachment`, peer)).status, 403);
    assert.equal((await request(`teacher/assignment-submissions/${submission._id}/grade`, teacher, 'PATCH', { score: 60, revision: submission.revision })).status, 200);
    const quiz = await Quiz.create({ courseId: course._id, title: 'Quiz', passingScore: 50, timeLimit: 10, attemptLimit: 3 });
    for (const [index, score] of [90, 60].entries()) await Attempt.create({ quizId: quiz._id, courseId: course._id, userId: student._id, status: 'submitted', score, passed: true, expiresAt: new Date(), submittedAt: new Date(1000 + index) });
    const progress = (await request(`courses/${course._id}/progress`, student)).body.data;
    const book = (await request(`teacher/courses/${course._id}/gradebook`)).body.data;
    const row = book.rows.find(r => r.student.id === String(student._id));
    assert.equal(progress.eligibleToComplete, true); assert.equal(row.result.eligibleToComplete, true);
    assert.equal(row.cells.find(c => c.key === `quiz:${quiz._id}`).score, 60);
    assert.equal('finalGrade' in row.result, false);
    const completed = await Promise.all([request(`enrollments/${enrollment._id}/complete`, student, 'POST', {}), request(`student/courses/${course._id}/lessons/${lesson._id}/complete`, student, 'POST', {})]);
    assert.deepEqual(completed.map(r => r.status), [200, 200]); assert.equal(await Certificate.countDocuments({ userId: student._id }), 1);
    const again = await request(`student/courses/${course._id}/lessons/${lesson._id}/complete`, student, 'POST', {});
    assert.equal(again.body.data.isCompleted, true); assert.equal(await Certificate.countDocuments({ userId: student._id }), 1);
  });
  await t.test('Late file retry is blocked; accepted submission preserved; latest resubmit invalidates readiness', async () => {
    await Assignment.updateOne({ _id: assignment._id }, { deadline: new Date(0) });
    assert.equal((await request(`student/assignments/${assignment._id}/submissions`, student, 'POST', multipart({ answer: '' }))).status, 409);
    assert.equal((await Submission.findById(submission._id)).score, 60);
    await Assignment.updateOne({ _id: assignment._id }, { deadline: new Date('2030-01-01') });
    const current = await Submission.findById(submission._id);
    const updated = await request(`student/assignments/${assignment._id}/submissions`, student, 'POST', multipart({ answer: '', revision: current.revision }, pdf, 'New-answer.pdf'));
    assert.equal(updated.status, 200); stored.add(updated.body.data.submission.attachment.storageKey);
    assert.equal(updated.body.data.submission.score, null);
    assert.equal((await request(`enrollments/${enrollment._id}/complete`, student, 'POST', {})).status, 422);
    const courses = (await request('student/courses', student)).body.data.courses;
    assert.equal(courses[0].enrollmentStatus, 'active'); assert.equal(courses[0].eligibleToComplete, false);
    assert.equal((await request('student/certificates', student)).body.data.certificates.length, 0);
    const report = (await request(`teacher/courses/${course._id}/grade-report`)).body.data;
    const book = (await request(`teacher/courses/${course._id}/gradebook`)).body.data;
    assert.deepEqual(report.rows, book.rows);
    assert.equal((await request(`teacher/courses/${course._id}/gradebook/policy`, teacher, 'PUT', { passingScore: 10 })).status, 410);
  });
});
