  updateQuiz: (id, data) => api(`/api/teacher/quizzes/${id}`, { method: 'PATCH', body: JSON.stringify(data) }),
  deleteQuiz: (id) => api(`/api/teacher/quizzes/${id}`, { method: 'DELETE' }),
  createQuestion: (quizId, data) => api(`/api/teacher/quizzes/${quizId}/questions`, { method: 'POST', body: JSON.stringify(data) }),
  listQuestions: (params = {}) => { const query = new URLSearchParams(Object.entries(params).filter(([, value]) => value !== undefined && value !== null && value !== '')); return api(`/api/teacher/questions${query.size ? `?${query}` : ''}`); },
  getQuestion: (id) => api(`/api/teacher/questions/${id}`),
  createBankQuestion: (data) => api('/api/teacher/questions', { method: 'POST', body: JSON.stringify(data) }),
