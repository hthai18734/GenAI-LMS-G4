  deleteCourse: (id) => api(`/api/teacher/courses/${id}`, { method: 'DELETE' }),
  submitForReview: (id) => api(`/api/teacher/courses/${id}/submit-review`, { method: 'POST' }),
  publish: (id) => api(`/api/teacher/courses/${id}/publish`, { method: 'POST' }),
  unpublish: (id) => api(`/api/teacher/courses/${id}/unpublish`, { method: 'POST' }),
  archive: (id) => api(`/api/teacher/courses/${id}/archive`, { method: 'POST' }),
  restore: (id) => api(`/api/teacher/courses/${id}/restore`, { method: 'POST' }),
